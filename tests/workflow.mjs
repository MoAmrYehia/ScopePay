import {chromium} from 'playwright';
import assert from 'node:assert/strict';
const browser=await chromium.launch({executablePath:process.env.CHROMIUM_PATH||'/usr/bin/chromium',headless:true,args:['--no-sandbox']});
const page=await browser.newPage({viewport:{width:1440,height:1100}});const errors=[];page.on('pageerror',e=>errors.push(e.message));
await page.goto('http://127.0.0.1:3000');
await page.getByRole('button',{name:'Review evidence'}).first().click();
assert(await page.getByRole('button',{name:'Client: approve milestone'}).isDisabled());
await page.getByRole('button',{name:'+ Add evidence'}).click();
await page.locator('#evidence-file').setInputFiles({name:'portfolio-page.png',mimeType:'image/png',buffer:Buffer.from('demo screenshot')});
await page.getByRole('button',{name:'Attach evidence'}).click();
await page.getByRole('button',{name:'Client: approve milestone'}).click();
await page.getByRole('button',{name:'Create demo invoice'}).click();
await page.getByRole('button',{name:'Simulate payment'}).click();
await page.getByRole('button',{name:'Done',exact:true}).click();
await page.reload();
assert(await page.getByText('$1,500',{exact:true}).isVisible());
await page.getByRole('button',{name:'Invoices',exact:true}).click();
assert(await page.getByText('Paid · demo',{exact:true}).isVisible());
await page.getByRole('button',{name:'New project'}).click();
await page.getByRole('button',{name:'Extract agreement'}).click();
assert.equal(await page.getByRole('button',{name:'+ Add evidence'}).count(),5);
await page.getByRole('button',{name:'Close dialog'}).click();
await page.getByRole('button',{name:'Overview',exact:true}).click();
await page.screenshot({path:'/tmp/scopepay-desktop.png',fullPage:true});
await page.setViewportSize({width:390,height:844});
assert(await page.evaluate(()=>document.documentElement.scrollWidth<=window.innerWidth));
await page.screenshot({path:'/tmp/scopepay-mobile.png',fullPage:true});
assert.deepEqual(errors,[]);console.log('PASS: missing-evidence guard, upload, approval, invoice, payment, persistence, agreement extraction, mobile layout, and no browser errors');
await browser.close();
